static const unsigned char *
get_glyph(char ch)
{
    int idx = (int)((unsigned char)ch) - 32;
    if (idx < 0 || idx >= (int)(sizeof(font_data) / sizeof(font_data[0])))
        return font_data[0];  /* space fallback */
    return font_data[idx];
}

/* ── Shader compilation ────────────────────────────────────────────────── */

static GLuint
compile_shader(GLenum type, const char *src)
{
    GLuint shader = glCreateShader(type);
    glShaderSource(shader, 1, &src, NULL);
    glCompileShader(shader);

    GLint compiled;
    glGetShaderiv(shader, GL_COMPILE_STATUS, &compiled);
    if (!compiled) {
        GLint log_len;
        glGetShaderiv(shader, GL_INFO_LOG_LENGTH, &log_len);
        char *log = (char *)malloc((size_t)(log_len + 1));
        if (log) {
            glGetShaderInfoLog(shader, log_len, NULL, log);
            fprintf(stderr, "[E] shell render: shader compile error: %s\n", log);
            free(log);
        }
        glDeleteShader(shader);
        return 0;
    }
    return shader;
}

static int
init_shaders(void)
{
    if (g_shader_program)
        return 0;  /* Already initialized */

    GLuint vs = compile_shader(GL_VERTEX_SHADER, vertex_shader_src);
    GLuint fs = compile_shader(GL_FRAGMENT_SHADER, fragment_shader_src);
    if (!vs || !fs) {
        if (vs) glDeleteShader(vs);
        if (fs) glDeleteShader(fs);
        return -1;
    }

    g_shader_program = glCreateProgram();
    glAttachShader(g_shader_program, vs);
    glAttachShader(g_shader_program, fs);
    glLinkProgram(g_shader_program);

    GLint linked;
    glGetProgramiv(g_shader_program, GL_LINK_STATUS, &linked);
    if (!linked) {
        fprintf(stderr, "[E] shell render: shader link error\n");
        glDeleteProgram(g_shader_program);
        g_shader_program = 0;
        glDeleteShader(vs);
        glDeleteShader(fs);
        return -1;
    }

    g_u_color_loc = glGetUniformLocation(g_shader_program, "u_color");
    glDeleteShader(vs);
    glDeleteShader(fs);
    return 0;
}

/* ── Public API ────────────────────────────────────────────────────────── */

void
render_init(int screen_width, int screen_height)
{
    g_screen_w = screen_width;
    g_screen_h = screen_height;

    glViewport(0, 0, screen_width, screen_height);

    /* Enable alpha blending for smooth text + overlays */
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    if (init_shaders() != 0) {
        fprintf(stderr, "[E] shell render: shader initialization failed\n");
    }
}

void
render_begin_frame(float r, float g, float b, float a)
{
    glClearColor(r, g, b, a);
    glClear(GL_COLOR_BUFFER_BIT);
    glUseProgram(g_shader_program);
}

void
render_end_frame(struct playos_shell *s)
{
    (void)s;
    /* No-op — eglSwapBuffers is called by main.c */
}

void
render_draw_rect(float x, float y, float w, float h,
                 float r, float g, float b, float a)
{
    if (!g_shader_program) return;

    /* Normalize screen-space coordinates to [-1, 1] */
    float nx1 = (x / (float)g_screen_w) * 2.0f - 1.0f;
    float ny1 = 1.0f - (y / (float)g_screen_h) * 2.0f;     /* top */
    float nx2 = ((x + w) / (float)g_screen_w) * 2.0f - 1.0f;
    float ny2 = 1.0f - ((y + h) / (float)g_screen_h) * 2.0f; /* bottom */

    GLfloat vertices[] = {
        nx1, ny1, 0.0f,
        nx2, ny1, 0.0f,
        nx1, ny2, 0.0f,
        nx2, ny2, 0.0f,
    };

    GLint pos_loc = glGetAttribLocation(g_shader_program, "a_pos");
    glEnableVertexAttribArray((GLuint)pos_loc);
    glVertexAttribPointer((GLuint)pos_loc, 3, GL_FLOAT, GL_FALSE, 0, vertices);

    glUniform4f(g_u_color_loc, r, g, b, a);
    glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
    glDisableVertexAttribArray((GLuint)pos_loc);
}

void
render_draw_text(const char *text, float x, float y,
                 float scale, float r, float g, float b, float a)
{
    if (!g_shader_program || !text) return;

    float cursor = x;
    float glyph_pixel_w = (FONT_W + FONT_SPACING) * scale;
    float glyph_pixel_h = (FONT_H + 1) * scale;

    for (const char *c = text; *c; c++) {
        if (*c == '\n') {
            cursor = x;
            y += glyph_pixel_h;
            continue;
        }

        const unsigned char *glyph = get_glyph(*c);

        for (unsigned int row = 0; row < FONT_H; row++) {
            unsigned char bits = glyph[row];
            for (unsigned int col = 0; col < FONT_W; col++) {
                if (bits & (1u << (4u - col))) {
                    /* Draw one pixel-sized rectangle */
                    float px = cursor + (float)col * scale;
                    float py = y + (float)row * scale;
                    render_draw_rect(px, py, scale, scale, r, g, b, a);
                }
            }
        }
        cursor += glyph_pixel_w;
    }
}

void
render_screen_dims(int *w, int *h)
{
    if (w) *w = g_screen_w;
    if (h) *h = g_screen_h;
}

float
render_text_width(const char *text, float scale)
{
    if (!text) return 0.0f;

    /* Find the longest line */
    float max_w = 0.0f;
    float cur_w = 0.0f;

    for (const char *c = text; *c; c++) {
        if (*c == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0.0f;
        } else {
            cur_w += (FONT_W + FONT_SPACING) * scale;
        }
    }
    if (cur_w > max_w) max_w = cur_w;

    return max_w;
}
